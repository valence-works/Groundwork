/// <summary>
/// States how a provider-native query plan is interpreted for one measured data shape.
/// </summary>
public enum NativePlanAssertionMode
{
    /// <summary>
    /// The indexed query must select the declared index and avoid a scan of its
    /// predicate-bearing relation.
    /// </summary>
    RequireDeclaredIndex,

    /// <summary>
    /// Retain the provider-native plan as a workload characterization without
    /// treating an optimizer-selected scan as a correctness failure.
    /// </summary>
    ScanCharacterization
}

/// <summary>
/// The reviewed selectivity policy for the physical-storage benchmark protocol.
/// The 10% shape proves the scale-bearing indexed-query contract. The 50% shape
/// remains measured and captures its real native plan, where a scan can be a
/// legitimate optimizer choice rather than an index-contract failure.
/// </summary>
public static class BenchmarkSelectivityPolicy
{
    public const int IndexedQueryAcceptanceBasisPoints = 1_000;
    public const int ScanCharacterizationBasisPoints = 5_000;

    public static NativePlanAssertionMode PlanAssertionModeFor(BenchmarkDataShape shape)
    {
        ArgumentNullException.ThrowIfNull(shape);
        shape.Validate();
        return shape.QuerySelectivityBasisPoints == ScanCharacterizationBasisPoints
            ? NativePlanAssertionMode.ScanCharacterization
            : NativePlanAssertionMode.RequireDeclaredIndex;
    }
}

/// <summary>
/// Describes an immutable, versioned payload generated by the benchmark harness.
/// The catalog below is deliberately closed: scheduled evidence may name only a
/// reviewed catalog member, and a data shape carries the whole claim so artifacts
/// and fingerprints cannot silently lose the bytes that were actually written.
/// </summary>
public sealed record BenchmarkPayloadProfile(
    string Id,
    string Version,
    string CanonicalTemplate,
    string CanonicalTemplateDigest,
    int PaddingBytes,
    BenchmarkPayloadEntropy Entropy,
    string ContentShape,
    IReadOnlyList<BenchmarkWorkload> ApplicableWorkloads,
    bool Reviewed)
{
    public bool Equals(BenchmarkPayloadProfile? other) =>
        other is not null &&
        Id.Equals(other.Id, StringComparison.Ordinal) &&
        Version.Equals(other.Version, StringComparison.Ordinal) &&
        CanonicalTemplate.Equals(other.CanonicalTemplate, StringComparison.Ordinal) &&
        CanonicalTemplateDigest.Equals(other.CanonicalTemplateDigest, StringComparison.Ordinal) &&
        PaddingBytes == other.PaddingBytes &&
        Entropy == other.Entropy &&
        ContentShape.Equals(other.ContentShape, StringComparison.Ordinal) &&
        Reviewed == other.Reviewed &&
        ApplicableWorkloads.SequenceEqual(other.ApplicableWorkloads);

    public override int GetHashCode()
    {
        var hash = new HashCode();
        hash.Add(Id, StringComparer.Ordinal);
        hash.Add(Version, StringComparer.Ordinal);
        hash.Add(CanonicalTemplate, StringComparer.Ordinal);
        hash.Add(CanonicalTemplateDigest, StringComparer.Ordinal);
        hash.Add(PaddingBytes);
        hash.Add(Entropy);
        hash.Add(ContentShape, StringComparer.Ordinal);
        hash.Add(Reviewed);
        foreach (var workload in ApplicableWorkloads)
            hash.Add(workload);
        return hash.ToHashCode();
    }

    public void Validate()
    {
        if (string.IsNullOrWhiteSpace(Id) || string.IsNullOrWhiteSpace(Version) ||
            string.IsNullOrWhiteSpace(CanonicalTemplate) ||
            string.IsNullOrWhiteSpace(CanonicalTemplateDigest) ||
            string.IsNullOrWhiteSpace(ContentShape) || PaddingBytes < 0 ||
            ApplicableWorkloads.Count == 0 ||
            ApplicableWorkloads.Distinct().Count() != ApplicableWorkloads.Count)
        {
            throw new InvalidOperationException("Benchmark payload-profile identity is incomplete or ambiguous.");
        }
        if (!CanonicalTemplateDigest.Equals(
                BenchmarkPayloadProfiles.DigestTemplate(CanonicalTemplate),
                StringComparison.Ordinal))
        {
            throw new InvalidOperationException("Benchmark payload-profile template digest does not match its canonical template.");
        }
    }

    public bool AppliesTo(BenchmarkWorkload workload) => ApplicableWorkloads.Contains(workload);
}

public enum BenchmarkPayloadEntropy
{
    DeterministicFixedCharacter
}

public static class BenchmarkPayloadProfiles
{
    public const string CanonicalTemplate =
        "{\"status\":\"{status}\",\"rank\":{rank},\"category\":\"{category}\",\"padding\":{padding:null-or-fixed-x-utf8-bytes}}";
    public const string OrdinaryJsonV1 = "ordinary-json-v1";
    public const string StorageGrowth1KiBV1 = "storage-growth-1k-v1";

    private static readonly IReadOnlyList<BenchmarkWorkload> OrdinaryWorkloads =
        Array.AsReadOnly(
            Enum.GetValues<BenchmarkWorkload>()
                .Where(workload => workload != BenchmarkWorkload.StorageGrowth)
                .ToArray());
    private static readonly IReadOnlyList<BenchmarkWorkload> StorageGrowthWorkloads =
        Array.AsReadOnly(new[] { BenchmarkWorkload.StorageGrowth });
    private static readonly IReadOnlyDictionary<string, BenchmarkPayloadProfile> ReviewedById =
        new Dictionary<string, BenchmarkPayloadProfile>(StringComparer.Ordinal)
        {
            [OrdinaryJsonV1] = CreateReviewed(
                OrdinaryJsonV1,
                paddingBytes: 0,
                "json/object/status-rank-category-padding-null",
                OrdinaryWorkloads),
            [StorageGrowth1KiBV1] = CreateReviewed(
                StorageGrowth1KiBV1,
                paddingBytes: 1_024,
                "json/object/status-rank-category-padding-fixed-x-utf8",
                StorageGrowthWorkloads)
        };

    public static IReadOnlyList<string> DefaultReviewedIds { get; } =
        Array.AsReadOnly(new[] { OrdinaryJsonV1, StorageGrowth1KiBV1 });

    public static BenchmarkPayloadProfile For(BenchmarkWorkload workload) => workload == BenchmarkWorkload.StorageGrowth
        ? GetReviewed(StorageGrowth1KiBV1)
        : GetReviewed(OrdinaryJsonV1);

    public static BenchmarkPayloadProfile GetReviewed(string id)
    {
        if (!ReviewedById.TryGetValue(id, out var profile))
            throw new InvalidOperationException($"Unknown reviewed benchmark payload profile '{id}'.");
        return profile;
    }

    public static BenchmarkPayloadProfile CreateLegacyPadding(int paddingBytes)
    {
        return new BenchmarkPayloadProfile(
            $"legacy-padding-{paddingBytes}-unreviewed",
            "legacy-v1",
            CanonicalTemplate,
            DigestTemplate(CanonicalTemplate),
            paddingBytes,
            BenchmarkPayloadEntropy.DeterministicFixedCharacter,
            "json/object/status-rank-category-padding-fixed-x-utf8",
            Array.AsReadOnly(Enum.GetValues<BenchmarkWorkload>()),
            Reviewed: false);
    }

    public static void ValidateClosed(BenchmarkPayloadProfile profile)
    {
        ArgumentNullException.ThrowIfNull(profile);
        profile.Validate();
        if (profile.Reviewed)
        {
            if (!ReviewedById.TryGetValue(profile.Id, out var expected) || expected != profile)
                throw new InvalidOperationException("Benchmark payload profile is not an exact reviewed catalog member.");
            return;
        }

        var expectedLegacy = CreateLegacyPadding(profile.PaddingBytes);
        if (expectedLegacy != profile)
            throw new InvalidOperationException("Unreviewed benchmark payload profile is not a canonical legacy smoke profile.");
    }

    public static string DigestTemplate(string template)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(template);
        return Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(
                System.Text.Encoding.UTF8.GetBytes(template)))
            .ToLowerInvariant();
    }

    private static BenchmarkPayloadProfile CreateReviewed(
        string id,
        int paddingBytes,
        string contentShape,
        IReadOnlyList<BenchmarkWorkload> workloads) => new(
        id,
        "v1",
        CanonicalTemplate,
        DigestTemplate(CanonicalTemplate),
        paddingBytes,
        BenchmarkPayloadEntropy.DeterministicFixedCharacter,
        contentShape,
        workloads,
        Reviewed: true);

}

public sealed record BenchmarkDataShape(
    int DatasetSize,
    BenchmarkPayloadProfile PayloadProfile,
    int QuerySelectivityBasisPoints)
{
    public BenchmarkDataShape(int datasetSize, int legacyPayloadPaddingBytes, int querySelectivityBasisPoints)
        : this(datasetSize, BenchmarkPayloadProfiles.CreateLegacyPadding(legacyPayloadPaddingBytes), querySelectivityBasisPoints)
    {
    }

    public int PayloadPaddingBytes => PayloadProfile.PaddingBytes;

    public string Identity =>
        $"n{DatasetSize}-profile{PayloadProfile.Id}-selectivity{QuerySelectivityBasisPoints}bp";

    public int GetSelectedDocumentCount()
    {
        Validate();
        return checked((int)(((long)DatasetSize * QuerySelectivityBasisPoints + 9_999) / 10_000));
    }

    public bool IsSelectedDocument(int zeroBasedIndex)
    {
        if (zeroBasedIndex < 0 || zeroBasedIndex >= DatasetSize)
            throw new ArgumentOutOfRangeException(nameof(zeroBasedIndex));
        return (long)zeroBasedIndex * 10_000 / DatasetSize < QuerySelectivityBasisPoints;
    }

    public void Validate()
    {
        if (DatasetSize <= 0)
            throw new InvalidOperationException("The benchmark dataset size must be positive.");
        BenchmarkPayloadProfiles.ValidateClosed(PayloadProfile);
        if (QuerySelectivityBasisPoints is <= 0 or >= 10_000)
        {
            throw new InvalidOperationException(
                "Query selectivity must be between 1 and 9,999 basis points so selection workloads remain observable.");
        }
    }
}

public sealed record BenchmarkMatrixDimensions(
    IReadOnlyList<int> DatasetSizes,
    IReadOnlyList<int> PayloadPaddingBytes,
    IReadOnlyList<int> QuerySelectivityBasisPoints,
    int IndependentRuns)
{
    /// <summary>
    /// A profile is selected per workload, rather than becoming a Cartesian matrix
    /// dimension. That keeps the ratified 4,032-worker schedule intact while
    /// making StorageGrowth's 1 KiB payload a truthful execution input.
    /// </summary>
    public IReadOnlyList<string>? PayloadProfileIds { get; init; }

    public IReadOnlyList<BenchmarkDataShape> CreateShapes(BenchmarkWorkload workload)
    {
        Validate();
        var profiles = ProfilesFor(workload);
        return DatasetSizes
            .SelectMany(size => profiles.SelectMany(profile =>
                QuerySelectivityBasisPoints.Select(selectivity =>
                    new BenchmarkDataShape(size, profile, selectivity))))
            .ToArray();
    }

    public void Validate()
    {
        if (DatasetSizes.Count == 0 || PayloadPaddingBytes.Count == 0 || QuerySelectivityBasisPoints.Count == 0)
            throw new InvalidOperationException("Dataset, payload, and selectivity dimensions must all contain values.");
        if (IndependentRuns <= 0)
            throw new InvalidOperationException("At least one independent run is required.");
        if (DatasetSizes.Distinct().Count() != DatasetSizes.Count ||
            PayloadPaddingBytes.Distinct().Count() != PayloadPaddingBytes.Count ||
            QuerySelectivityBasisPoints.Distinct().Count() != QuerySelectivityBasisPoints.Count)
            throw new InvalidOperationException("Benchmark matrix dimensions cannot contain duplicate values.");
        if (PayloadProfileIds is { Count: 0 })
            throw new InvalidOperationException("Benchmark payload-profile selections cannot be empty.");
        if (PayloadProfileIds is not null)
        {
            if (PayloadPaddingBytes.Any(padding => padding != 0))
            {
                throw new InvalidOperationException(
                    "Reviewed payload-profile selections cannot be combined with a raw payload-padding dimension.");
            }
            if (PayloadProfileIds.Distinct(StringComparer.Ordinal).Count() != PayloadProfileIds.Count)
                throw new InvalidOperationException("Benchmark payload-profile selections cannot contain duplicates.");
            foreach (var id in PayloadProfileIds)
                BenchmarkPayloadProfiles.GetReviewed(id);
        }
        foreach (var shape in CreateUncheckedShapes())
            shape.Validate();
    }

    private IEnumerable<BenchmarkDataShape> CreateUncheckedShapes() =>
        DatasetSizes.SelectMany(size => PayloadPaddingBytes.SelectMany(payload =>
            QuerySelectivityBasisPoints.Select(selectivity => new BenchmarkDataShape(size, payload, selectivity))));

    private IReadOnlyList<BenchmarkPayloadProfile> ProfilesFor(BenchmarkWorkload workload)
    {
        if (PayloadProfileIds is null)
            return PayloadPaddingBytes.Select(BenchmarkPayloadProfiles.CreateLegacyPadding).ToArray();

        return PayloadProfileIds
            .Select(BenchmarkPayloadProfiles.GetReviewed)
            .Where(profile => profile.AppliesTo(workload))
            .ToArray();
    }
}

public sealed record BenchmarkRunConfiguration(
    string SchemaVersion,
    BenchmarkRunMode Mode,
    int Seed,
    int DatasetSize,
    int MigrationDatasetSize,
    int WarmupIterations,
    int MeasurementIterations,
    int OperationsPerIteration,
    int Concurrency,
    IReadOnlyList<BenchmarkProvider> Providers,
    IReadOnlyList<PhysicalStorageForm> StorageForms)
{
    public BenchmarkDataShape? DataShape { get; init; }
    public int MinimumMeasuredOperations { get; init; } = 1;
    public int MinimumSteadyStateDurationSeconds { get; init; }

    public void Validate()
    {
        if (SchemaVersion != BenchmarkProfiles.SchemaVersion)
            throw new InvalidOperationException($"Unsupported benchmark schema '{SchemaVersion}'.");
        if (DatasetSize <= 0 || MigrationDatasetSize <= 0)
            throw new InvalidOperationException("Dataset sizes must be positive.");
        if (WarmupIterations < 1 || MeasurementIterations < 5 || OperationsPerIteration < 1 || Concurrency < 1)
            throw new InvalidOperationException("Warmup, measurement, operation, and concurrency settings are below the reproducibility floor.");
        if (MinimumMeasuredOperations < 1 || MinimumSteadyStateDurationSeconds < 0)
            throw new InvalidOperationException("Measured operation and steady-state duration floors cannot be negative or empty.");
        if (Mode == BenchmarkRunMode.Scheduled &&
            (MinimumMeasuredOperations < 100 || MinimumSteadyStateDurationSeconds < 30))
        {
            throw new InvalidOperationException(
                "Scheduled workers require at least 100 measured operations and 30 seconds of steady-state execution.");
        }
        if (Providers.Count == 0 || StorageForms.Count == 0)
            throw new InvalidOperationException("At least one provider and storage form must be selected.");
        if (DataShape is not null)
        {
            DataShape.Validate();
            if (DataShape.DatasetSize != DatasetSize)
                throw new InvalidOperationException("The execution data shape must match the fixed dataset-size control.");
            if (Mode == BenchmarkRunMode.Scheduled && !DataShape.PayloadProfile.Reviewed)
            {
                throw new InvalidOperationException(
                    "Scheduled workers require an exact reviewed benchmark payload profile; raw padding is smoke-only.");
            }
        }
    }
}

